const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('github-pages/app.js','utf8');
new vm.Script(source);
const start=source.indexOf('  function heroMinutes('),end=source.indexOf('  function heroStatus()',start);
assert.ok(start>0&&end>start);
const ctx=vm.createContext({Date,Map,String,Number,Math});
vm.runInContext(source.slice(start,end),ctx);
const snapshot={date:'2099-11-18',at:1000000,ranges:ctx.parseHeroRanges('Campo 1;19:00;22:00;scoperto\nCampo 5;20:00;20:30;coperto','2099-11-18')};
const req={date:'2099-11-18',time:'20:00',duration:90,tolerance:30};
const r=ctx.heroCandidates(snapshot,req,1000010);
assert.equal(r.status,'available');assert.equal(r.slots.length,3);assert.equal(r.slots[0].start,'20:00');assert.equal(r.slots[0].end,'21:30');assert.equal(r.slots[0].manual,true);assert.equal(r.slots[0].price,'');
assert.equal(r.slots[0].cover,'outdoor');assert.ok(r.slots.every(x=>x.court==='Campo 1'));
assert.equal(ctx.heroCandidates(snapshot,{...req,date:'2099-11-19'},1000010).status,'manual_required');
assert.equal(ctx.heroCandidates(snapshot,req,1600001).status,'manual_required');
assert.equal(ctx.heroCandidates(snapshot,{...req,time:'23:00',tolerance:0},1000010).status,'manual_required');
assert.throws(()=>ctx.parseHeroRanges('Campo;22:00;19:30','2099-11-18'));
assert.throws(()=>ctx.parseHeroRanges('Campo;19:15;22:30','2099-11-18'));
assert.throws(()=>ctx.parseHeroRanges('Campo;19:00;22:00','2099-02-30'));
assert.doesNotMatch(source,/PBL_CHROME\.query/);
assert.match(source,/candidate Playtomic da confermare/);
assert.match(source,/loadAll\(\);\s*probePlaytomic\(\);/);
for(const file of ['index.html','github-pages/index.html'])assert.match(fs.readFileSync(file,'utf8'),/id="heroImportForm"/);
console.log('v1.27: candidati assistiti, date e durata, scadenza e assenza di lettura API verificati.');

const exact={date:req.date,at:1000000,ranges:ctx.parseHeroRanges('Campo 6 INDOOR;19:15;20:45;coperto;slot',req.date)};
const exactReq={...req,time:'19:15',tolerance:30};
const exactResult=ctx.heroCandidates(exact,exactReq,1000010);
assert.equal(exactResult.slots.length,1);assert.equal(exactResult.slots[0].start,'19:15');assert.equal(exactResult.slots[0].end,'20:45');
assert.equal(ctx.heroCandidates(exact,{...exactReq,duration:60},1000010).slots.length,0);
assert.throws(()=>ctx.parseHeroRanges('Campo 6;19:00;19:30;;slot',req.date));
assert.throws(()=>ctx.parseHeroRanges('Campo 6;19:00;20:30;;other',req.date));
console.log('v1.27: importazione della fascia selezionata con durata esatta.');

assert.match(source,/heroOpen\(\{\.\.\.req,key\}\)/);
assert.match(source,/pbl-hero-imported/);
assert.match(source,/data\.key!==heroPending\.key/);
assert.match(source,/heroCandidates\(heroFresh\(req\)\?heroSnapshot:null,req\)/);
assert.match(source,/visibilitychange/);
console.log('v1.27: acquisizione diretta e filtro delle richieste obsolete.');
